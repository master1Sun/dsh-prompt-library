/** 把命名空间合并进框架的类型表，让 register / t 座位获得键级类型推导。 */
declare module "@deepseek-ai/dsh-client-ui-slots" {
  interface LocaleNamespaceMap {
    "prompt-library": keyof typeof zh;
  }
}

/** 本命名空间的类型化翻译函数（组件注入的 `t` 座位类型）。 */
export type PLTranslate = TranslateNS<typeof NS>;

/** 词库翻译键的联合类型（供动态拼键时断言使用）。 */
export type PLKey = keyof typeof zh;

/**
 * 组件内统一取翻译函数：优先用框架注入的 `t`（跟随系统语言切换），
 * 未注入时（如侧边栏独立渲染）回退到中文字典，保证功能可用。
 */
export type PLT = (key: keyof typeof zh, params?: Record<string, unknown>) => string;

/** 回退翻译：直接用中文字典渲染文案，并替换 `{name}` 占位符。 */
export function fallbackT(key: keyof typeof zh, params?: Record<string, unknown>): string {
  let text: string = zh[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}

/**
 * 插件 apply 时登记的宿主翻译函数（随系统语言动态取词）。
 *
 * 右侧面板等座位由宿主直接渲染，不一定注入 `t` prop；这里登记一份模块级回退，
 * 让这些组件也能跟随宿主语言切换，而不是固定回退中文。
 */
let boundT: PLTranslate | null = null;

/** apply 时登记 `ctx.locale.bind(NS)` 的结果。 */
export function setBoundT(fn: PLTranslate | null): void {
  boundT = fn;
}

/** 语言切换事件名：由插件 apply 订阅宿主 locale 后广播，供面板组件重渲染。 */
export const LOCALE_CHANGED_EVENT = "pl:locale-changed";

/**
 * 强制刷新计数：宿主语言切换后触发，供不注入 `t` 的座位（右侧面板）重渲染。
 * 与 usePLT 配合即可实现完整的面板国际化。
 */
export function useLocaleVersion(): number {
  const [version, setVersion] = useState(0);
  useEffect(() => {
    const onChange = (): void => setVersion((v) => v + 1);
    window.addEventListener(LOCALE_CHANGED_EVENT, onChange);
    return () => window.removeEventListener(LOCALE_CHANGED_EVENT, onChange);
  }, []);
  return version;
}

/** 组件内取 t：优先框架注入的 t，其次模块级登记 t，最后回退中文。 */
export function usePLT(t?: PLTranslate): PLT {
  useLocaleVersion(); // 订阅语言切换，保证切换后重新取词
  const base = (t ?? boundT ?? fallbackT) as PLT;
  return (key, params) => {
    let text = base(key, params);
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        // 宿主 t 可能不处理占位符，统一再替换一次 `{name}`，避免界面出现原文
        text = text.split(`{${k}}`).join(String(v));
      }
    }
    return text;
  };
}
